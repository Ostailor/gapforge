def render_config(*, run_type: str, workspace_id: str, metrics: list[MetricRecord]) -> str:
    payload = {
        "workspace_id": workspace_id,
        "run_type": run_type,
        "smoke_only": run_type == "smoke",
        "metric_ids": [record.id for record in metrics],
        "results": "not run",
    }
    return json.dumps(payload, indent=2) + "\n"


