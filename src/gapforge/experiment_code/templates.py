def render_readme(
    *,
    workspace_id: str,
    protocol: ExperimentProtocol | None,
    datasets: list[DatasetRecord],
    baselines: list[BaselineRecord],
    metrics: list[MetricRecord],
) -> str:
    lines = [
        f"# Experiment Code Scaffold `{workspace_id}`",
        "",
        "This directory is a runnable scaffold generated by GapForge. It contains smoke tests and implementation placeholders.",
        "",
        "It does not contain real experimental results. No experiment results are included. Smoke output validates wiring only.",
        "",
        "## Protocol",
        "",
        f"- Protocol ID: `{protocol.id if protocol else 'none'}`",
        f"- Objective: {protocol.objective if protocol else 'not specified'}",
        f"- Hypothesis: {protocol.hypothesis if protocol else 'not specified'}",
        "",
        "## Registered Datasets",
        "",
    ]
    lines.extend([f"- `{record.id}` {record.name} ({record.dataset_type})" for record in datasets] or ["- none registered"])
    lines.extend(["", "## Registered Baselines", ""])
    lines.extend([f"- `{record.id}` {record.name} ({record.baseline_type})" for record in baselines] or ["- none registered"])
    lines.extend(["", "## Registered Metrics", ""])
    lines.extend(
        [f"- `{record.id}` {record.name}: {record.formula or 'formula not specified'}" for record in metrics] or ["- none registered"]
    )
    lines.extend(
        [
            "",
            "## Codex Implementation Notes",
            "",
            "- Replace placeholder dataset loaders with documented, versioned dataset access.",
            "- Implement required baselines before using this for paper-quality claims.",
            "- Keep fixture/synthetic data visibly labeled.",
            "- Add result writing only through GapForge execution records and result artifacts.",
            "- Do not write fake measured results into this scaffold.",
            "",
            "## Smoke",
            "",
            "```bash",
            "bash scripts/run_smoke.sh",
            "```",
            "",
        ]
    )
    return "\n".join(lines)


def render_data_py(datasets: list[DatasetRecord], protocol: ExperimentProtocol | None) -> str:
    dataset_payload = [
        {
            "id": record.id,
            "name": record.name,
            "dataset_type": record.dataset_type,
            "local_path": record.local_path,
            "is_fixture_or_synthetic": record.dataset_type in {"fixture", "synthetic", "generated"},
        }
        for record in datasets
    ]
    protocol_datasets = protocol.datasets if protocol else []
    return f'''"""Dataset loading placeholders.

Fixture and synthetic records are only for smoke tests. They cannot support empirical claims.
"""

from __future__ import annotations


DATASET_REGISTRY = {pformat(dataset_payload, width=100)}
PROTOCOL_DATASETS = {pformat(protocol_datasets, width=100)}


def dataset_names() -> list[str]:
    if DATASET_REGISTRY:
        return [str(item["name"]) for item in DATASET_REGISTRY]
    return list(PROTOCOL_DATASETS)


def load_fixture_records() -> list[dict[str, object]]:
    """Return clearly labeled fixture records for smoke tests only."""
    return [
        {{"id": "fixture-negative-1", "label": 0, "score": 0.05, "is_fixture": True}},
        {{"id": "fixture-positive-1", "label": 1, "score": 0.95, "is_fixture": True}},
    ]
'''


def render_baselines_py(baselines: list[BaselineRecord], protocol: ExperimentProtocol | None) -> str:
    names = [record.name for record in baselines]
    if not names and protocol is not None:
        names = [candidate.baseline_name for candidate in protocol.baselines if candidate.baseline_name]
    return f'''"""Baseline placeholders.

These functions are interfaces for implementation. They are not measured baseline results.
"""

from __future__ import annotations


BASELINES = {json.dumps(names, indent=4)}


def baseline_names() -> list[str]:
    return list(BASELINES)


def score_threshold_baseline(records: list[dict[str, object]], *, threshold: float = 0.5) -> list[int]:
    """Simple smoke-only threshold baseline over fixture scores."""
    return [1 if float(record.get("score", 0.0)) >= threshold else 0 for record in records]
'''


def render_metrics_py(metrics: list[MetricRecord], protocol: ExperimentProtocol | None) -> str:
    metric_names = [record.name for record in metrics] or (protocol.metrics if protocol else [])
    return f'''"""Metric implementations for smoke tests and future real experiments."""

from __future__ import annotations


METRICS = {json.dumps(metric_names, indent=4)}


def metric_names() -> list[str]:
    return list(METRICS)


def confusion_counts(labels: list[int], predictions: list[int]) -> dict[str, int]:
    if len(labels) != len(predictions):
        raise ValueError("labels and predictions must have the same length")
    tp = sum(1 for label, pred in zip(labels, predictions, strict=True) if label == 1 and pred == 1)
    tn = sum(1 for label, pred in zip(labels, predictions, strict=True) if label == 0 and pred == 0)
    fp = sum(1 for label, pred in zip(labels, predictions, strict=True) if label == 0 and pred == 1)
    fn = sum(1 for label, pred in zip(labels, predictions, strict=True) if label == 1 and pred == 0)
    return {{"tp": tp, "tn": tn, "fp": fp, "fn": fn}}


def false_positive_rate(labels: list[int], predictions: list[int]) -> float:
    counts = confusion_counts(labels, predictions)
    denominator = counts["fp"] + counts["tn"]
    return 0.0 if denominator == 0 else counts["fp"] / denominator


def true_positive_rate(labels: list[int], predictions: list[int]) -> float:
    counts = confusion_counts(labels, predictions)
    denominator = counts["tp"] + counts["fn"]
    return 0.0 if denominator == 0 else counts["tp"] / denominator


def precision(labels: list[int], predictions: list[int]) -> float:
    counts = confusion_counts(labels, predictions)
    denominator = counts["tp"] + counts["fp"]
    return 0.0 if denominator == 0 else counts["tp"] / denominator


def recall(labels: list[int], predictions: list[int]) -> float:
    return true_positive_rate(labels, predictions)
'''


def render_run_experiment_py(workspace_id: str) -> str:
    return f'''"""Smoke runner for the GapForge experiment scaffold.

This module intentionally does not produce empirical result claims.
"""

from __future__ import annotations

import json

from baselines import score_threshold_baseline
from data import load_fixture_records
from metrics import false_positive_rate, precision, recall, true_positive_rate


def run_smoke() -> dict[str, object]:
    records = load_fixture_records()
    labels = [int(record["label"]) for record in records]
    predictions = score_threshold_baseline(records)
    return {{
        "workspace_id": "{workspace_id}",
        "status": "smoke_only",
        "fixture_data": True,
        "results": "not run",
        "wiring_metrics": {{
            "false_positive_rate": false_positive_rate(labels, predictions),
            "true_positive_rate": true_positive_rate(labels, predictions),
            "precision": precision(labels, predictions),
            "recall": recall(labels, predictions),
        }},
    }}


if __name__ == "__main__":
    print(json.dumps(run_smoke(), indent=2, sort_keys=True))
'''


