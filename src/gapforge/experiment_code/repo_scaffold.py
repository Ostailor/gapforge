"""Create minimal experiment repositories for implementation handoff."""

from __future__ import annotations

import json
import re
from pathlib import Path

from gapforge.config import GapForgeConfig
from gapforge.experiment_code.eval_scripts import (
    baseline_names,
    metric_definitions,
    render_eval_script,
    render_reproducibility_lines,
)
from gapforge.experiment_code.task_generator import load_experiment_code_context
from gapforge.models import ExperimentProtocol, ExperimentRepoScaffold, Provenance
from gapforge.project_memory import ProjectMemoryManager
from gapforge.state import utc_now_iso


class ExperimentRepoScaffolder:
    """Write a safe, smoke-testable experiment repository skeleton."""

    def __init__(self, config: GapForgeConfig) -> None:
        self.config = config
        self.project_manager = ProjectMemoryManager(config)

    def scaffold(
        self,
        *,
        campaign_id: str,
        direction_id: str,
        allow_rejected: bool = False,
    ) -> ExperimentRepoScaffold:
        context = load_experiment_code_context(
            self.config,
            campaign_id=campaign_id,
            direction_id=direction_id,
            allow_rejected=allow_rejected,
        )
        root = Path(context.program.project.root_dir) / "experiment_repos" / direction_id
        package_name = _package_name(direction_id)
        files = _scaffold_files(context.protocol, package_name)
        for relative, content in files.items():
            path = root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        (root / "src" / package_name).mkdir(parents=True, exist_ok=True)
        scaffold = ExperimentRepoScaffold(
            id=f"experiment-repo-{direction_id}",
            direction_id=direction_id,
            path=str(root),
            files=sorted(files),
            created_at=utc_now_iso(),
            provenance=Provenance(
                created_by_skill="experiment-repo-scaffold",
                source_ids=[campaign_id, direction_id, context.protocol.id],
                timestamp=utc_now_iso(),
                reasoning_summary=(
                    "Created a minimal experiment implementation scaffold with placeholder data clearly labeled, "
                    "smoke tests, protocol metrics, and reproducibility notes. No results were generated."
                ),
            ),
        )
        context.program.experiment_repo_scaffolds = [item for item in context.program.experiment_repo_scaffolds if item.id != scaffold.id]
        context.program.experiment_repo_scaffolds.append(scaffold)
        self.project_manager.save_project(context.program)
        return scaffold


def _scaffold_files(protocol: ExperimentProtocol, package_name: str) -> dict[str, str]:
    datasets = protocol.datasets or ["SYNTHETIC PLACEHOLDER DATA ONLY"]
    files = {
        "README.md": _readme(protocol),
        "pyproject.toml": _pyproject(package_name),
        f"src/{package_name}/__init__.py": '"""Experiment scaffold package. No research results are included."""\n',
        f"src/{package_name}/datasets.py": _datasets_py(datasets),
        f"src/{package_name}/metrics.py": _metrics_py(protocol),
        f"src/{package_name}/baselines.py": _baselines_py(protocol),
        "tests/test_smoke.py": _smoke_test(package_name),
        "configs/default.json": json.dumps(_default_config(protocol), indent=2) + "\n",
        "data/README.md": _data_readme(protocol),
        "metrics/definitions.py": _metrics_py(protocol),
        "metrics/README.md": _metrics_readme(protocol),
        "baselines/README.md": _baselines_readme(protocol),
        "evals/run_eval.py": render_eval_script(protocol),
    }
    return files


def _readme(protocol: ExperimentProtocol) -> str:
    lines = [
        f"# Experiment Scaffold for `{protocol.direction_id}`",
        "",
        "This repository is an implementation scaffold generated by GapForge. It contains no experiment results.",
        "",
        "## Objective",
        "",
        protocol.objective or "Not specified.",
        "",
        "## Hypothesis",
        "",
        protocol.hypothesis or "Not specified.",
        "",
        "## Datasets",
        "",
    ]
    if protocol.datasets:
        lines.extend([f"- {dataset}" for dataset in protocol.datasets])
    else:
        lines.append("- SYNTHETIC PLACEHOLDER DATA ONLY. Replace before any real experiment.")
    lines.extend(["", "## Baselines", ""])
    lines.extend([f"- {name}" for name in baseline_names(protocol.baselines)])
    lines.extend(["", "## Metrics", ""])
    lines.extend([f"- {definition}" for definition in metric_definitions(protocol)])
    lines.extend(["", "## Reproducibility Checklist", ""])
    lines.extend([f"- {line}" for line in render_reproducibility_lines(protocol.reproducibility_checklist)])
    lines.extend(
        [
            "",
            "## Honesty Rules",
            "",
            "- Do not claim experiment results until a real run is completed and logged.",
            "- Synthetic placeholder data must remain visibly labeled.",
            "- Expected results are hypotheses, not observations.",
            "",
        ]
    )
    return "\n".join(lines)


def _pyproject(package_name: str) -> str:
    return f"""[project]
name = "{package_name.replace("_", "-")}"
version = "0.0.0"
description = "GapForge experiment scaffold; contains no experiment results."
requires-python = ">=3.11"
dependencies = []

[project.optional-dependencies]
dev = ["pytest>=8"]

[tool.pytest.ini_options]
testpaths = ["tests"]
pythonpath = ["src"]
"""


def _datasets_py(datasets: list[str]) -> str:
    dataset_list = ", ".join(repr(item) for item in datasets)
    return f'''"""Dataset interfaces for the experiment scaffold.

Synthetic placeholder data is clearly labeled and must not be treated as a real benchmark.
"""

from __future__ import annotations


DATASETS = [{dataset_list}]


def load_placeholder_records() -> list[dict[str, object]]:
    return [
        {{"id": "synthetic-placeholder-1", "label": "SYNTHETIC_PLACEHOLDER", "is_placeholder": True}},
    ]
'''


def _metrics_py(protocol: ExperimentProtocol) -> str:
    metrics = protocol.metrics or ["primary_metric"]
    metric_list = ", ".join(repr(item) for item in metrics)
    return f'''"""Metric definitions from the GapForge protocol."""

from __future__ import annotations


METRICS = [{metric_list}]


def metric_names() -> list[str]:
    return list(METRICS)
'''


def _baselines_py(protocol: ExperimentProtocol) -> str:
    names = baseline_names(protocol.baselines)
    baseline_list = ", ".join(repr(item) for item in names)
    return f'''"""Baseline registry for implementation.

These are interfaces/TODOs, not completed baseline results.
"""

from __future__ import annotations


BASELINES = [{baseline_list}]


def baseline_names() -> list[str]:
    return list(BASELINES)
'''


def _smoke_test(package_name: str) -> str:
    return f"""from {package_name}.datasets import load_placeholder_records
from {package_name}.metrics import metric_names


def test_placeholder_data_is_labeled() -> None:
    records = load_placeholder_records()
    assert records
    assert all(record.get("is_placeholder") is True for record in records)


def test_metrics_are_defined() -> None:
    assert metric_names()
"""


def _default_config(protocol: ExperimentProtocol) -> dict[str, object]:
    return {
        "direction_id": protocol.direction_id,
        "protocol_id": protocol.id,
        "datasets": protocol.datasets,
        "metrics": protocol.metrics,
        "smoke_only": True,
        "results": "not run",
    }


def _data_readme(protocol: ExperimentProtocol) -> str:
    if protocol.datasets:
        datasets = "\n".join(f"- {dataset}" for dataset in protocol.datasets)
        return f"# Data\n\nProtocol datasets:\n\n{datasets}\n\nNo dataset files are committed by this scaffold.\n"
    return (
        "# Data\n\n"
        "SYNTHETIC PLACEHOLDER DATA ONLY.\n\n"
        "Replace this directory with documented, versioned data before running a real experiment.\n"
    )


def _metrics_readme(protocol: ExperimentProtocol) -> str:
    return "# Metrics\n\n" + "\n".join(f"- {definition}" for definition in metric_definitions(protocol)) + "\n"


def _baselines_readme(protocol: ExperimentProtocol) -> str:
    return "# Baselines\n\n" + "\n".join(f"- {name}" for name in baseline_names(protocol.baselines)) + "\n"


def _package_name(direction_id: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9_]+", "_", direction_id).strip("_").lower()
    if not slug or slug[0].isdigit():
        slug = f"experiment_{slug}"
    return slug
