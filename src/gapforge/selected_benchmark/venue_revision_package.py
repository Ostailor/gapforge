"""Post-remediation venue revision package for selected benchmark manuscripts."""

from __future__ import annotations

import json
import shutil
from dataclasses import dataclass, field
from pathlib import Path

from gapforge.artifact_eval.package import ArtifactEvaluationPackageExporter
from gapforge.config import GapForgeConfig
from gapforge.manuscript.bibliography import ManuscriptBibliographyManager
from gapforge.manuscript.manager import ManuscriptManager
from gapforge.manuscript.submission_checklist import SubmissionChecklistManager, render_submission_checklist_markdown
from gapforge.models import Provenance, to_plain
from gapforge.project_memory import ProjectMemoryManager
from gapforge.selected_benchmark.artifact_package_loader import ArtifactPackageLoader
from gapforge.selected_benchmark.related_work_matrix_loader import RelatedWorkMatrixLoader
from gapforge.selected_benchmark.spec import SelectedBenchmarkManager
from gapforge.selected_benchmark.venue_artifact_integration import VenueArtifactIntegrationManager
from gapforge.state import slugify, utc_now_iso

PACKAGE_STATUSES = {"workshop_candidate", "conference_candidate", "revise_for_reviews", "no_go"}


@dataclass(slots=True)
class VenueRevisionPackage:
    id: str
    manuscript_id: str
    venue_profile_id: str
    status: str
    files: list[str] = field(default_factory=list)
    related_work_matrix_id: str = ""
    artifact_package_id: str = ""
    drastic_review_id: str = ""
    revision_plan_id: str = ""
    limitations: list[str] = field(default_factory=list)
    provenance: Provenance = field(default_factory=lambda: Provenance(created_by_skill="selected-venue-revision-package"))


class VenueRevisionPackageManager:
    """Export an auditable venue package after drastic-review remediation."""

    def __init__(self, config: GapForgeConfig) -> None:
        self.config = config
        self.config.ensure_dirs()
        self.projects = ProjectMemoryManager(config)
        self.benchmarks = SelectedBenchmarkManager(config)
        self.manuscripts = ManuscriptManager(config)
        self.bibliography = ManuscriptBibliographyManager(config)
        self.checklists = SubmissionChecklistManager(config)
        self.related_work = RelatedWorkMatrixLoader(config)
        self.artifact_packages = ArtifactPackageLoader(config)
        self.venue_integration = VenueArtifactIntegrationManager(config)
        from gapforge.reviewers.drastic_panel import DrasticReviewPanelBuilder

        self.drastic = DrasticReviewPanelBuilder(config)

    def create(self, benchmark_id: str) -> VenueRevisionPackage:
        spec = self.benchmarks.load_spec(benchmark_id)
        integration = self.venue_integration.integrate(spec.id)
        related = self.related_work.load(spec.id)
        artifact = self.artifact_packages.load(spec.id)
        manuscript_id = integration.manuscript_id or related.manuscript_id or artifact.manuscript_id
        state = self.manuscripts.load_state(manuscript_id)
        root = self.manuscripts.manuscript_root(manuscript_id)
        blockers = list(integration.blockers)
        blockers.extend(_hard_artifact_blockers(related.status, related.blockers, "related-work matrix"))
        blockers.extend(_hard_artifact_blockers(artifact.status, artifact.blockers, "artifact evaluation package"))
        blockers.extend(_fake_citation_blockers(root, state_sections=[section.content_path for section in state.sections]))

        bibliography_error = ""
        try:
            bibliography = self.bibliography.build(manuscript_id)
        except (FileNotFoundError, ValueError) as exc:
            bibliography = None
            bibliography_error = str(exc)
        checklist = self.checklists.build(manuscript_id)
        rerun = self.drastic.rerun_manuscript(manuscript_id)
        from gapforge.reviewers.drastic_panel import render_drastic_review_rerun_result

        status = _package_status(
            hard_blockers=blockers,
            remaining_fatal=rerun.remaining_blockers,
            checklist_blockers=checklist.blocking_issues,
        )
        limitations = _dedupe(
            [
                *integration.warnings,
                *blockers,
                *rerun.remaining_blockers,
                *checklist.blocking_issues,
                *(["Bibliography blocked: " + bibliography_error] if bibliography_error else []),
                "No copied venue prose is generated by this package.",
                "No fake citations, fake results, or synthetic deployment-validity claims are allowed.",
                "Synthetic selected-benchmark evidence remains separate from real public benchmark/no-fit evidence.",
            ]
        )
        package_id = f"venue-revision-package-{slugify(spec.id)}"
        package_dir = self._package_dir(spec.project_id, package_id)
        if package_dir.exists():
            shutil.rmtree(package_dir)
        package_dir.mkdir(parents=True, exist_ok=True)

        files = _write_package_files(
            config=self.config,
            manuscript_root=root,
            package_dir=package_dir,
            manuscript_id=manuscript_id,
            related_matrix_path=related.selected_path,
            artifact_package_id=artifact.selected_package_id,
            checklist_markdown=render_submission_checklist_markdown(checklist),
            rerun_markdown=render_drastic_review_rerun_result(rerun),
            bibliography_built=bibliography is not None,
        )
        package = VenueRevisionPackage(
            id=package_id,
            manuscript_id=manuscript_id,
            venue_profile_id=state.manuscript.target_venue or checklist.venue_template_id,
            status=status,
            files=files,
            related_work_matrix_id=related.matrix_id,
            artifact_package_id=artifact.selected_package_id,
            drastic_review_id=rerun.new_review_id,
            revision_plan_id=f"drastic-revision-plan-{slugify(manuscript_id)}",
            limitations=limitations,
            provenance=Provenance(
                created_by_skill="selected-venue-revision-package",
                source_ids=_dedupe(
                    [
                        spec.id,
                        manuscript_id,
                        integration.id,
                        related.matrix_id,
                        artifact.selected_package_id,
                        rerun.id,
                        checklist.manuscript_id,
                    ]
                ),
                timestamp=utc_now_iso(),
                reasoning_summary=(
                    "Exported post-remediation venue revision package from existing manuscript and artifact state without "
                    "inventing citations, results, or readiness."
                ),
            ),
        )
        (package_dir / "venue_revision_package.json").write_text(json.dumps(to_plain(package), indent=2) + "\n", encoding="utf-8")
        (package_dir / "README.md").write_text(render_venue_revision_package(package), encoding="utf-8")
        package.files = _relative_files(package_dir)
        (package_dir / "venue_revision_package.json").write_text(json.dumps(to_plain(package), indent=2) + "\n", encoding="utf-8")
        (package_dir / "README.md").write_text(render_venue_revision_package(package), encoding="utf-8")
        self._write_latest(spec.project_id, package)
        return package

    def status(self, benchmark_id: str) -> str:
        spec = self.benchmarks.load_spec(benchmark_id)
        path = self._latest_path(spec.project_id)
        if not path.exists():
            package = self.create(spec.id)
        else:
            from gapforge.models import from_dict

            package = from_dict(VenueRevisionPackage, json.loads(path.read_text(encoding="utf-8")))
        return render_venue_revision_package(package)

    def _write_latest(self, project_id: str, package: VenueRevisionPackage) -> None:
        path = self._latest_path(project_id)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(to_plain(package), indent=2) + "\n", encoding="utf-8")
        path.with_suffix(".md").write_text(render_venue_revision_package(package), encoding="utf-8")

    def _latest_path(self, project_id: str) -> Path:
        program = self.projects.load_project(project_id)
        return Path(program.project.root_dir) / "selected_benchmark" / "venue_revision_package" / "latest.json"

    def _package_dir(self, project_id: str, package_id: str) -> Path:
        program = self.projects.load_project(project_id)
        return Path(program.project.root_dir) / "selected_benchmark" / "venue_revision_package" / package_id


def render_venue_revision_package(package: VenueRevisionPackage) -> str:
    lines = [
        f"# Venue Revision Package `{package.id}`",
        "",
        f"- Manuscript ID: `{package.manuscript_id}`",
        f"- Venue profile ID: `{package.venue_profile_id}`",
        f"- Status: `{package.status}`",
        f"- Related-work matrix: `{package.related_work_matrix_id or 'none'}`",
        f"- Artifact package: `{package.artifact_package_id or 'none'}`",
        f"- Drastic review: `{package.drastic_review_id or 'none'}`",
        f"- Revision plan: `{package.revision_plan_id or 'none'}`",
        f"- Files: {len(package.files)}",
        "",
        "## Package Boundary",
        "",
    ]
    if package.status == "conference_candidate":
        lines.append("- Fatal drastic-review blockers are resolved, but final conference readiness still requires external release gates.")
    elif package.status == "workshop_candidate":
        lines.append("- This package is labeled `workshop_candidate`; it must not be presented as conference-ready.")
    elif package.status == "revise_for_reviews":
        lines.append("- Fatal or major review issues remain; use this as a revision package, not a submission package.")
    else:
        lines.append("- This package is `no_go`; missing or unsafe evidence blocks venue use.")
    lines.extend(
        [
            "- No copied venue-style prose is generated.",
            "- No fake citations or fake results are allowed.",
            "- Synthetic benchmark evidence is not deployment-validity evidence.",
            "",
            "## Limitations",
            "",
        ]
    )
    lines.extend([f"- {item}" for item in package.limitations] or ["- none"])
    lines.extend(["", "## Files", ""])
    lines.extend([f"- `{item}`" for item in package.files] or ["- none"])
    return "\n".join(lines).rstrip() + "\n"


def _write_package_files(
    *,
    config: GapForgeConfig,
    manuscript_root: Path,
    package_dir: Path,
    manuscript_id: str,
    related_matrix_path: str,
    artifact_package_id: str,
    checklist_markdown: str,
    rerun_markdown: str,
    bibliography_built: bool,
) -> list[str]:
    _write_manuscript(manuscript_root, package_dir)
    if bibliography_built:
        _copy_optional_dir(manuscript_root / "bibliography", package_dir / "bibliography")
    _copy_file(Path(related_matrix_path), package_dir / "related_work_matrix" / Path(related_matrix_path).name)
    if artifact_package_id:
        try:
            artifact_dir = ArtifactEvaluationPackageExporter(config).package_dir(artifact_package_id)
            _copy_optional_dir(artifact_dir, package_dir / "artifact_evaluation_package")
        except FileNotFoundError:
            pass
    _copy_optional_file(
        manuscript_root / "selected_benchmark" / "real_benchmark_search" / "real_benchmark_no_fit_report.md",
        package_dir / "real_benchmark" / "real_benchmark_no_fit_report.md",
    )
    _copy_optional_file(
        manuscript_root.parent.parent / "selected_benchmark" / "real_benchmark_search" / "real_benchmark_no_fit_report.md",
        package_dir / "real_benchmark" / "real_benchmark_no_fit_report.md",
    )
    _copy_optional_file(
        manuscript_root.parent.parent / "selected_benchmark" / "real_benchmark_experiments" / "real_benchmark_experiment_attempts.md",
        package_dir / "real_benchmark" / "real_benchmark_experiment_attempts.md",
    )
    _copy_optional_dir(manuscript_root / "reviews" / "drastic", package_dir / "drastic_review")
    (package_dir / "revision_delta.md").write_text(rerun_markdown, encoding="utf-8")
    _copy_limitations(manuscript_root, package_dir)
    (package_dir / "submission_checklist.md").write_text(checklist_markdown, encoding="utf-8")
    _copy_optional_file(manuscript_root / "submission" / "artifact_appendix.md", package_dir / "artifact_appendix.md")
    return _relative_files(package_dir)


def _write_manuscript(manuscript_root: Path, package_dir: Path) -> None:
    state_path = manuscript_root / "manuscript.json"
    state = json.loads(state_path.read_text(encoding="utf-8"))
    title = state.get("manuscript", {}).get("title", "Venue-shaped manuscript")
    lines = [f"# {title}", ""]
    for section in state.get("sections", []):
        section_path = manuscript_root / str(section.get("content_path", ""))
        if section_path.exists():
            lines.append(section_path.read_text(encoding="utf-8").rstrip())
            lines.append("")
    (package_dir / "venue_shaped_manuscript.md").write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    _copy_file(state_path, package_dir / "manuscript.json")


def _copy_limitations(manuscript_root: Path, package_dir: Path) -> None:
    state = json.loads((manuscript_root / "manuscript.json").read_text(encoding="utf-8"))
    parts = ["# Limitations", ""]
    for section in state.get("sections", []):
        if section.get("section_type") != "limitations":
            continue
        section_path = manuscript_root / str(section.get("content_path", ""))
        if section_path.exists():
            parts.append(section_path.read_text(encoding="utf-8").rstrip())
    if len(parts) == 2:
        parts.append("No limitations section is currently recorded.")
    (package_dir / "limitations.md").write_text("\n\n".join(parts).rstrip() + "\n", encoding="utf-8")


def _fake_citation_blockers(root: Path, *, state_sections: list[str]) -> list[str]:
    from gapforge.reviewers.drastic_panel import validate_review_text_no_fake_citations

    blockers = []
    for relative in state_sections:
        path = root / relative
        if not path.exists():
            continue
        try:
            validate_review_text_no_fake_citations(path.read_text(encoding="utf-8"))
        except ValueError as exc:
            blockers.append(f"Fake or unaudited citation-shaped text blocked in `{relative}`: {exc}")
    return blockers


def _package_status(
    *,
    hard_blockers: list[str],
    remaining_fatal: list[str],
    checklist_blockers: list[str],
) -> str:
    if hard_blockers:
        return "no_go"
    if remaining_fatal:
        return "revise_for_reviews"
    if checklist_blockers:
        return "workshop_candidate"
    return "conference_candidate"


def _hard_artifact_blockers(status: str, blockers: list[str], label: str) -> list[str]:
    if status in {"loaded", "repaired"} and not blockers:
        return []
    return [f"Venue revision package requires loadable {label}.", *blockers]


def _copy_optional_dir(source: Path, destination: Path) -> None:
    if not source.exists():
        return
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(source, destination)


def _copy_file(source: Path, destination: Path) -> None:
    if not source.exists():
        return
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination)


def _copy_optional_file(source: Path, destination: Path) -> None:
    _copy_file(source, destination)


def _relative_files(package_dir: Path) -> list[str]:
    return sorted(str(path.relative_to(package_dir)) for path in package_dir.rglob("*") if path.is_file())


def _dedupe(items: list[str]) -> list[str]:
    result = []
    seen: set[str] = set()
    for item in items:
        if item and item not in seen:
            result.append(item)
            seen.add(item)
    return result
